#!/usr/bin/env python3
"""Reference pipeline: infer the history, then scan for sweeps against it.

Order matters.  The history has to come first, because the null distribution
a sweep must stand out from is the one generated by that history on this
recombination map.  The DETECTION thresholds are calibrated at run time
against simulations of the fitted history, rather than against the genome's
own empirical distribution, which already contains both the bottleneck and
the sweeps.

The characterisation constants are not calibrated at run time at all: they
are fixed numbers in characterize.py, fitted offline on single-sweep
replicates simulated under the TRUE demography (see that module's docstring
and authoring/evidence/).  An analyst doing this for real would fit them on
simulations of their own fitted history, which is one error term this
reference does not carry and a different implementation would.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

import numpy as np

if __package__ in (None, ""):
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    from pipeline import characterize as CH
    from pipeline import demography as DEM
    from pipeline import detect as DET
    from pipeline import sweepstats as SS
else:
    from . import characterize as CH
    from . import demography as DEM
    from . import detect as DET
    from . import sweepstats as SS

WIN = 50_000
STEP = 10_000


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--vcf", default="/app/data/variants.vcf.gz")
    ap.add_argument("--rate-map", default="/app/data/recombination_map.bed")
    ap.add_argument("--out", default="/app/results.json")
    ap.add_argument("--mu", type=float, default=2.0e-8)
    ap.add_argument("--n-null", type=int, default=10)
    ap.add_argument("--expected-false", type=float, default=0.3)
    ap.add_argument("--form-quantile", type=float, default=0.99,
                    help="null quantile at which clusters are formed")
    ap.add_argument("--seed", type=int, default=20_240_101)
    ap.add_argument("--dump-scan", default=None,
                    help="authoring aid: save the windowed scan, the scores "
                         "and the called regions to this .npz so the "
                         "characterisation step can be re-derived without "
                         "re-running the eight-minute pipeline")
    a = ap.parse_args(argv)

    t_start = time.time()

    def log(msg):
        print(f"[{time.time() - t_start:7.1f}s] {msg}", flush=True)

    log("loading genotypes")
    chroms = SS.load_vcf(a.vcf)
    n_snps = sum(c.pos.size for c in chroms.values())
    n_dip = next(iter(chroms.values())).n_hap // 2
    log(f"  {len(chroms)} chromosomes, {n_snps} SNPs, {n_dip} diploids")

    rm = DET.load_rate_map(a.rate_map)
    med_rate = rm.median_rate()
    log(f"  recombination map: {rm.n_chrom} chromosomes of {rm.chrom_len} bp, "
        f"median rate {med_rate:.3g}")

    log("fitting the demographic history to the site frequency spectrum")
    obs_sum = DEM.observed_summaries(chroms, rm.chrom_len)
    log(f"  background diversity {obs_sum['pi']:.4g} over {obs_sum['n_snps']} SNPs")
    hist, dist = DEM.fit_demography(obs_sum, mu=a.mu, rate=med_rate,
                                    n_dip=n_dip, seed=a.seed, log=log)
    log(f"  fitted: {hist.as_dict()}  (distance {dist:.4f})")

    log("scanning the observed genome")
    obs = DET.scan_genome(chroms, rm.chrom_len, rm, WIN, STEP)
    log(f"  {obs['pi'].size} windows")

    log(f"simulating {a.n_null} null replicates under the fitted history "
        f"with the real recombination map")
    null = DET.build_null(hist, rm, a.mu, n_dip, WIN, STEP,
                          n_reps=a.n_null, seed=a.seed + 5000, log=log)

    log("scoring windows against rate-matched null")
    score = DET.sweep_scores(obs, null, med_rate)
    null_score = DET.sweep_scores(null, null, med_rate)
    fin = null_score[np.isfinite(null_score)]
    form_thresh = float(np.quantile(fin, a.form_quantile))
    log(f"  cluster-forming threshold {form_thresh:.2f} "
        f"(null quantile {a.form_quantile})")

    mass_thresh = DET.calibrate_clusters(null, null_score, form_thresh,
                                         a.n_null, a.expected_false)
    log(f"  cluster-mass threshold {mass_thresh:.1f} "
        f"(expected {a.expected_false} null clusters per genome)")

    regions = DET.call_clusters(obs, score, form_thresh, mass_thresh)
    log(f"  {len(regions)} candidate region(s)")

    bins = DET.rate_bin(obs["rate"], med_rate)
    bg = CH.background_levels(obs, regions, bins)

    if a.dump_scan:
        np.savez_compressed(
            a.dump_scan,
            score=score, bins=bins, form_thresh=form_thresh,
            mass_thresh=mass_thresh,
            hist=json.dumps(hist.as_dict()),
            null_score=null_score, null_chrom=null["chrom"],
            null_mid=null["mid"],
            null_rep=(null["rep"] if "rep" in null
                      else np.zeros(null_score.size, dtype=np.int64)),
            n_null=a.n_null,
            regions=json.dumps([
                {k: (list(map(int, v)) if k == "window_indices"
                     else list(v) if k == "span" else v)
                 for k, v in r.items()} for r in regions]),
            **{f"obs_{k}": v for k, v in obs.items()})
        log(f"  scan dumped to {a.dump_scan}")

    calls = []
    for r in regions:
        b = int(bins[r["peak_index"]])
        lev = bg.get(b) or next(iter(bg.values()))
        local_rate = float(obs["rate"][r["peak_index"]])
        f = CH.features(obs, r, lev)
        f.update(CH.shape_features(obs, r, lev, local_rate))
        klass = CH.classify(f)
        s_hat = CH.estimate_s(f, klass)
        t_hat = CH.estimate_time(f, klass)
        call = {
            "chrom": int(r["chrom"]),
            "position": int(r["position"]),
            "class": klass,
            "selection_coefficient": float(s_hat) if np.isfinite(s_hat) else 0.01,
        }
        # A completion time for every call. The schema requires one on the
        # complete classes and ignores it on the partial ones, and the
        # verifier grades it against a sweep's TRUE class, so reporting it
        # everywhere costs nothing and saves the dates of any sweep this
        # pipeline classifies wrongly.
        if t_hat is not None:
            call["time_gens_ago"] = float(round(t_hat))
        calls.append(call)
        log(f"  chr{r['chrom']}:{r['position']:,} score={r['peak_score']:.1f} "
            f"pi={f['pi_ratio']:.3f} tajd={f['tajd_delta']:+.2f} "
            f"h2h1={f['h2h1_ratio']:.3f} nsl={f['nsl_delta']:+.3f} -> {klass} "
            f"s={s_hat:.4f} t={t_hat if t_hat is None else round(t_hat)}")

    result = {"demography": hist.as_dict(), "sweeps": calls}
    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    with open(a.out, "w") as fh:
        json.dump(result, fh, indent=2, sort_keys=True)
    log(f"wrote {a.out} with {len(calls)} sweep call(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
